-- Mirrors the SQLite schema in app/db/index.ts

create table public.tire_measurements (
  id bigint generated by default as identity primary key,
  position text not null,
  left_depth double precision,
  center_depth double precision,
  right_depth double precision,
  brand text,
  model text,

  size_width integer,          -- e.g., 225
  size_aspect_ratio integer,   -- e.g., 45
  size_diameter integer,       -- e.g., 17
  size_construction text,      -- 'R', 'B', or 'D'

  load_index text,
  speed_rating text,
  vehicle_make text,
  vehicle_model text,
  vehicle_year integer,
  weather_condition text,
  weather_temperature double precision,
  tire_cleanliness text,
  lighting_condition text,
  damage_type text,
  damage_description text,
  measurement_device text,
  original_video_url text,
  "timestamp" timestamptz default now()
);

create table public.frame_images (
  id bigint generated by default as identity primary key,
  tire_measurement_id bigint not null references public.tire_measurements (id) on delete cascade,
  frame_url text not null
);

create index frame_images_tire_measurement_id_idx on public.frame_images (tire_measurement_id);
create index tire_measurements_timestamp_idx on public.tire_measurements ("timestamp" desc);

-- No policies: only the server (service role / direct connection) can read or write.
alter table public.tire_measurements enable row level security;
alter table public.frame_images enable row level security;
